// Copies the browser page, the engine and the two examples into one flat
// folder that any static host can serve, e.g. as counterroll.dev/verify/.
// Nothing is minified or rewritten apart from the import paths.
//
//   node scripts/build-web.mjs [outDir]    (default: web-dist)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const out = resolve(process.argv[2] || join(root, 'web-dist'));
mkdirSync(out, { recursive: true });

// The example key is read from the README so the page and the README cannot
// drift apart.
const readme = readFileSync(join(root, 'README.md'), 'utf8');
const m = /\*\*For the two examples in this repository\*\* the key is:\s*```\s*([0-9a-f]{64})\s*```/.exec(readme);
if (!m) throw new Error('example key not found in README.md');

const read = (f) => readFileSync(join(root, f), 'utf8');
const copy = (from, to, fix = (s) => s) => writeFileSync(join(out, to), fix(read(from)));
copy('web/index.html', 'index.html');
copy('web/app.mjs', 'app.mjs', (s) => s.replaceAll("'../src/", "'./"));
copy('src/core.mjs', 'core.mjs');
writeFileSync(
  join(out, 'examples.mjs'),
  `// Generated by scripts/build-web.mjs from README.md and examples/. Do not edit.\n` +
    `export const EXAMPLE_KEY = ${JSON.stringify(m[1])};\n` +
    `export const ORIGINAL = ${read('examples/refusal-original.json').trim()};\n` +
    `export const EDITED = ${read('examples/refusal-edited.json').trim()};\n`,
);
console.log(`Wrote ${out}`);
